import { query as portalQuery } from "@/backend/db/db";
import type { Tx } from "../core/db";
import { hasFactoryPermission, type AuthzActor } from "../core/authz";
import { notFound } from "../core/errors";
import { coaHeader, reviewSignature } from "../qms/coa";
import { visibleOligoUnits } from "./orders";

function isAutoGeneratedPoCustomerLabel(label: string | null | undefined): boolean {
  const s = String(label ?? "").trim();
  if (!s) return true;
  if (/^Kho Thương Mại Kinh Doanh ABT$/i.test(s)) return true;
  if (/^PO\s+PO-/i.test(s)) return true;
  if (/^(?:PO\s+)?PO-[A-Z0-9-]+\s*(?:[—–-]|\()\s*(?:Bộ Primer\/Probe|Đơn tổng hợp Oligo|DN\d)/i.test(s)) return true;
  return false;
}

function stripLeadingPoCodePrefix(label: string | null | undefined): string {
  const s = String(label ?? "").trim();
  if (!s) return "";
  return s.replace(/^(?:PO\s+)?PO-[A-Z0-9-]+\s*[—–-]\s*/i, "").trim();
}

/**
 * Certificate of analysis of an Oligo order (as OligoFlow's "Phiếu phân tích chất lượng sản phẩm"): per sequence the
 * theoretical properties, the measured quantity and the results of its last passed, reviewed QC test (a pooled
 * sequence takes its pool master's). Sequences without a passed test are listed as such, never filled in.
 */
export async function orderCoa(tx: Tx, actor: AuthzActor, orderId: string) {
  const o = (
    await tx.query(
      `SELECT o.*,
              io.code AS internal_order_code,
              io.kd_po_code,
              io.kd_so_code,
              io.ship_to,
              ou.name AS org_unit_name,
              (SELECT COALESCE(ou_p.name, u2.name)
                 FROM core.user_profile up
                 LEFT JOIN core.org_unit ou_p ON ou_p.id = up.org_unit_id
                 LEFT JOIN core.user_role ur ON ur.user_id = up.user_id AND ur.revoked_at IS NULL
                 LEFT JOIN core.org_unit u2 ON u2.id = ur.scope_org_unit_id AND u2.unit_type = 'DEPARTMENT'
                WHERE up.user_id = COALESCE(io.created_by, o.created_by)
                LIMIT 1) AS creator_dept_name
         FROM oligo.oligo_order o
         LEFT JOIN intake.internal_order io ON io.id = o.internal_order_id
         LEFT JOIN core.org_unit ou ON ou.id = o.org_unit_id
        WHERE o.id = $1`,
      [orderId]
    )
  ).rows[0];
  const canViewFromIntake =
    Boolean(actor.isSalesIntakeUser) || (await hasFactoryPermission(tx, actor, "intake.order.view"));
  const units = o ? (canViewFromIntake ? "ALL" : await visibleOligoUnits(tx, actor)) : [];
  if (!o || (units !== "ALL" && !units.includes(o.org_unit_id))) throw notFound("đơn Oligo");

  // Resolve customer name (when transferred from Sales/Kinh doanh) or department name (when ordered internally by R&D, Kit, QA/QC, Oligo)
  let resolvedUnitOrCustomer = "";
  const shipToName = o.ship_to && typeof o.ship_to === "object" ? String((o.ship_to as any).name || "").trim() : "";
  if (shipToName && !isAutoGeneratedPoCustomerLabel(shipToName) && !/^Bệnh viện Đa khoa Trung ương \/ CDC$/i.test(shipToName)) {
    resolvedUnitOrCustomer = stripLeadingPoCodePrefix(shipToName);
  }
  if (!resolvedUnitOrCustomer && o.kd_so_code && !/^SO-KD-DN/i.test(String(o.kd_so_code))) {
    try {
      const soCodes = String(o.kd_so_code)
        .split(/[,;\s]+/)
        .map((s) => s.trim())
        .filter(Boolean);
      if (soCodes.length > 0) {
        const soRes = await portalQuery(
          "SELECT customer_name FROM sales_orders WHERE order_code = ANY($1::text[])",
          [soCodes]
        );
        const custNames = Array.from(
          new Set((soRes.rows ?? []).map((r: any) => String(r.customer_name || "").trim()).filter(Boolean))
        );
        if (custNames.length > 0) {
          resolvedUnitOrCustomer = custNames.join(" + ");
        }
      }
    } catch {
      // Fallback below if portal DB is unreachable in isolated unit test
    }
  }
  if (!resolvedUnitOrCustomer) {
    if (!isAutoGeneratedPoCustomerLabel(o.customer_label)) {
      resolvedUnitOrCustomer = stripLeadingPoCodePrefix(o.customer_label);
    } else {
      resolvedUnitOrCustomer = o.creator_dept_name || o.org_unit_name || "Phòng Tổng hợp Oligo";
    }
  }
  const seqs = (
    await tx.query(
      `SELECT s.id, s.code, s.name, s.normalized_sequence, s.base_count, s.molecule_type, s.product_type, s.oligo_role, s.target_pathogen,
              s.scale_code, s.purification, s.format, s.mw::float AS mw, s.tm::float AS tm,
              s.gc_percent::float AS gc_percent, s.ext_coeff_260::float AS ext_coeff_260, s.nmol_per_od::float AS nmol_per_od, s.ug_per_od::float AS ug_per_od, s.modifications, s.status,
              coalesce(m.id, s.id) AS tested_id
         FROM oligo.oligo_sequence s
         LEFT JOIN oligo.oligo_pool p ON p.id = s.pool_id AND s.status = 'POOLED' LEFT JOIN oligo.oligo_sequence m ON m.id = p.master_sequence_id
        WHERE s.order_id = $1 AND s.status NOT IN ('CANCELLED', 'SPLIT')
          AND NOT (s.status = 'FAILED' AND EXISTS (SELECT 1 FROM oligo.oligo_sequence r WHERE r.parent_sequence_id = s.id AND r.relation = 'RESYNTH'))
        ORDER BY s.line_no NULLS LAST, s.code`,
      [orderId]
    )
  ).rows;
  const sequences = [];
  for (const s of seqs) {
    const pp = (
      await tx.query("SELECT od_total::float AS od_total, nmol::float AS nmol, ug::float AS ug, tube_count FROM oligo.post_process WHERE sequence_id = $1 AND status = 'SUBMITTED'", [s.tested_id])
    ).rows[0];
    const test = (
      await tx.query(
        "SELECT id, code, reviewed_at FROM qms.qc_test WHERE entity_type = 'OLIGO_SEQUENCE' AND entity_id = $1 AND status = 'REVIEWED' AND overall_result = 'PASS' ORDER BY reviewed_at DESC LIMIT 1",
        [s.tested_id]
      )
    ).rows[0];
    const rawResults = test
      ? (
          await tx.query(
            `SELECT p.seq, p.name, p.unit, p.method, p.lower_limit::float AS lower_limit, p.upper_limit::float AS upper_limit, p.value_type, p.target, p.derived_metric,
                    r.value_numeric::float AS value_numeric, r.observed_numeric::float AS observed_numeric, r.value_text, r.passed
               FROM qms.qc_result r JOIN qms.qc_spec_parameter p ON p.id = r.parameter_id WHERE r.test_id = $1 ORDER BY p.seq`,
            [test.id]
          )
        ).rows
      : [];
    const scaleRaw = String(s.scale_code ?? "").trim().toUpperCase();
    const scaleNmolMatch = /1\s*U(MOL)?/i.test(scaleRaw) ? 1000 : Number((scaleRaw.match(/(\d+)\s*NMOL/i) ?? [])[1] || 100);
    const isProbeSeq = s.product_type === "PROBE" || (Array.isArray(s.modifications) && s.modifications.length > 0);
    const yieldRatio = isProbeSeq ? 0.15 : 0.3;
    const minNmolForScale = Math.round(scaleNmolMatch * yieldRatio * 100) / 100;
    const results = rawResults.map((r: any) => {
      if (r.derived_metric === "YIELD_NMOL" && (r.lower_limit == null || Number(r.lower_limit) <= 0.1)) {
        return {
          ...r,
          lower_limit: minNmolForScale,
          target: `> ${minNmolForScale} nmol`,
        };
      }
      return r;
    });
    const is_amplicon =
      Boolean(s.is_amplicon) ||
      s.product_type === "AMPLICON_LINEAR" ||
      s.product_type === "AMPLICON_PLASMID" ||
      s.oligo_role === "TEMPLATE" ||
      s.oligo_role === "POSITIVE_CONTROL";
    sequences.push({
      ...s,
      is_amplicon,
      measured: pp ?? null,
      qc: test ? { code: test.code, reviewed_at: test.reviewed_at, signature: await reviewSignature(tx, test.id), results } : null,
    });
  }
  const hasUnapproved = sequences.some((s: any) => s.status !== "COMPLETED" && s.status !== "DELIVERED");
  return {
    ...(await coaHeader(tx)),
    quarantine_watermark: hasUnapproved,
    order: {
      id: o.id,
      code: o.code,
      customer_label: resolvedUnitOrCustomer,
      kd_po_code: o.kd_po_code,
      internal_order_code: o.internal_order_code,
      due_date: o.due_date,
      notes: o.notes,
      created_at: o.created_at,
    },
    sequences,
  };
}
